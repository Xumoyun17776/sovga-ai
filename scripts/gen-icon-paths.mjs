// Generates client/src/lib/iconPaths.ts from Phosphor's icon definitions,
// keeping only the three weights the site uses (bold, duotone, fill).
// Run: node scripts/gen-icon-paths.mjs   (after adding an icon import to lib/icons.tsx)
import fs from "fs";
import path from "path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const src = fs.readFileSync(path.join(root, "client/src/lib/icons.tsx"), "utf8");
const names = [...new Set([...src.matchAll(/P\.([A-Z][A-Za-z0-9]*)/g)].map((m) => m[1]))].sort();
const out = {};
for (const n of names) {
  const mod = await import(path.join(root, "node_modules/@phosphor-icons/react/dist/defs", `${n}.es.js`));
  const map = mod.default || Object.values(mod)[0];
  out[n] = {};
  for (const w of ["bold", "duotone", "fill"]) {
    out[n][w] = renderToStaticMarkup(createElement("g", null, map.get(w))).replace(/^<g>|<\/g>$/g, "");
  }
}
const body =
  "// AUTO-GENERATED by scripts/gen-icon-paths.mjs — Phosphor Icons (MIT), bold/duotone/fill weights only.\n" +
  "export type IconPaths = { bold: string; duotone: string; fill: string };\n" +
  "export const P: Record<string, IconPaths> = " + JSON.stringify(out) + ";\n";
fs.writeFileSync(path.join(root, "client/src/lib/iconPaths.ts"), body);
console.log("icons:", names.length, "bytes:", body.length);
